import { CommunicationLink } from './link';

export type RouteOptimizationType = 'DEMO_GRAPH_SEARCH' | 'QAOA_QUANTUM' | 'QUBO_CLASSICAL';

export interface ConstellationRoute {
  pathId: string;
  sourceSatelliteId: string;
  destinationGroundStationId: string;
  nodeSequence: string[];          // e.g. ["SAT-01", "SAT-04", "SAT-08", "GS-SGS"]
  links: CommunicationLink[];
  totalLatencyMs: number;          // Estimated latency based on speed of light + processing
  bottleneckSinrDb: number;
  aggregatedRfiLevel: number;
  isFeasible: boolean;
  optimizationType: RouteOptimizationType;
  isBackendOptimized: boolean;     // False when generated by frontend demo search
  label: string;                   // "Demo Route — QAOA Backend Not Connected" or "QAOA Optimized"
}
